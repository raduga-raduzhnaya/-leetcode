class Solution {
public:
    vector<int> twoSum(vector<int>& nums, int target) {
        // Проходим по всем числам
        for (int i = 0; i < nums.size(); i++) {
            // Для каждого числа i ищем пару среди оставшихся
            for (int j = i + 1; j < nums.size(); j++) {
                // Если сумма равна цели
                if (nums[i] + nums[j] == target) {
                    // Возвращаем их индексы
                    return {i, j};
                }
            }
        }
        // Если ничего не нашли (хотя по условию ответ всегда есть)
        return {};
    }
};

// Алгоритм:
// 1. Внешний цикл (i) последовательно фиксирует первое число.
// 2. Внутренний цикл (j) перебирает все числа, идущие после i (j = i + 1).
// 3. Проверяем сумму nums[i] + nums[j] на равенство target.
// 4. Если сумма совпадает, возвращаем индексы {i, j}.
// 5. Если после всех итераций пара не найдена, возвращаем пустой вектор.
//
// Сложность:
// - По времени: O(N^2) из-за двух вложенных циклов.
// - По памяти: O(1), так как дополнительная память не выделяется.
