class Solution {
public:
    bool isRectangleOverlap(vector<int>& rec1, vector<int>& rec2) {
        // Проверяем пересечение проекций на ось X
        bool overlapX = max(rec1[0], rec2[0]) < min(rec1[2], rec2[2]);
        // Проверяем пересечение проекций на ось Y
        bool overlapY = max(rec1[1], rec2[1]) < min(rec1[3], rec2[3]);
        return overlapX && overlapY;
    }
};

// Алгоритм:
// 1. Проверяем пересечение проекций прямоугольников на ось X:
//    вычисляем max из левых границ и min из правых.
//    Если max < min, значит по оси X есть пересечение (overlapX = true).
// 2. Аналогично проверяем пересечение проекций на ось Y:
//    max из нижних границ и min из верхних.
//    Если max < min, значит по оси Y есть пересечение (overlapY = true).
// 3. Прямоугольники пересекаются, только если true и для X, и для Y.
//
// Сложность:
// - По времени: O(1) — выполняется фиксированное количество операций.
// - По памяти: O(1) — дополнительная память не используется.
