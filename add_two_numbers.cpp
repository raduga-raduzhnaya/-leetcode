class Solution {
public:
    ListNode* addTwoNumbers(ListNode* l1, ListNode* l2) {
        ListNode* head = nullptr; // Голова нового списка
        ListNode* curr = nullptr; // Текущий узел, который мы добавляем
        int carry = 0; // Перенос в следующий разряд

        // Идем по спискам, пока есть хоть один узел
        while (l1 != nullptr || l2 != nullptr) {
            // Берем значения из узлов. Если список закончился, считаем что там 0
            int x = 0;
            if (l1 != nullptr) {
                x = l1->val;
            }
            
            int y = 0;
            if (l2 != nullptr) {
                y = l2->val;
            }

            // Складываем цифры и перенос
            int sum = x + y + carry;
            
            // Вычисляем новый перенос и цифру для записи
            carry = sum / 10;
            int digit = sum % 10;

            // Создаем новый узел
            ListNode* newNode = new ListNode(digit);

            // Если это самый первый узел, то он становится головой
            if (head == nullptr) {
                head = newNode;
                curr = newNode;
            } else {
                // Иначе просто прикрепляем его в конец
                curr->next = newNode;
                curr = curr->next;
            }

            // Не забываем сдвинуть указатели в исходных списках
            if (l1 != nullptr) {
                l1 = l1->next;
            }
            if (l2 != nullptr) {
                l2 = l2->next;
            }
        }

        // Важный момент: если после цикла остался перенос (например, 99 + 1 = 100)
        // Нужно добавить еще один узел в конец
        if (carry > 0) {
            curr->next = new ListNode(carry);
        }

        return head;
    }
};


// Алгоритм (симуляция сложения в столбик):
// 1. Инициализируем указатели head и curr как nullptr для построения нового списка.
// 2. Инициализируем переменную carry = 0 для хранения переноса в следующий разряд.
// 3. Запускаем цикл while, пока есть узлы хотя бы в одном из списков (l1 или l2).
// 4. На каждой итерации извлекаем значения x и y из текущих узлов. 
//    Если узел равен nullptr, считаем его значение равным 0.
// 5. Вычисляем сумму: sum = x + y + carry.
// 6. Обновляем carry = sum / 10, а цифра для нового узла = sum % 10.
// 7. Создаем новый узел с полученной цифрой.
// 8. Если head == nullptr, новый узел становится головой (head) и текущим (curr).
//    Иначе прикрепляем новый узел в конец (curr->next) и сдвигаем curr.
// 9. Не забываем сдвинуть указатели l1 и l2 вперед, если они не nullptr.
// 10. После выхода из цикла проверяем: если carry > 0, добавляем еще один узел в конец.
// 11. Возвращаем head (голову результирующего списка).
//
// Сложность:
// - По времени: O(max(N, M)), где N и M — длины списков (один проход по более длинному списку).
// - По памяти: O(max(N, M)) для хранения нового списка (O(1) вспомогательной памяти).
